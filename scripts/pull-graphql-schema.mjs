import { buildClientSchema, getIntrospectionQuery, lexicographicSortSchema, printSchema } from 'graphql';
import { writeFile, rename } from 'node:fs/promises';
import nextEnv from '@next/env';
nextEnv.loadEnvConfig(process.cwd());
const endpoint = process.env.WORDPRESS_GRAPHQL_URL || 'https://zabawnekoszulki.pl/graphql';
const url = new URL(endpoint);
if (!['http:', 'https:'].includes(url.protocol) || url.username || url.password || url.search || url.hash) throw new Error('Invalid schema endpoint');
const response = await fetch(url, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ query: getIntrospectionQuery() }), signal: AbortSignal.timeout(60000) });
if (!response.ok) throw new Error(`Introspection HTTP ${response.status}`);
const payload = await response.json();
if (payload.errors?.length || !payload.data?.__schema) throw new Error('Introspection failed; previous schema retained');
const schema = lexicographicSortSchema(buildClientSchema(payload.data));
const destination = new URL('../graphql/schema.graphql', import.meta.url);
const temp = new URL('../graphql/schema.graphql.tmp', import.meta.url);
await writeFile(temp, '# Generated by npm run graphql:schema. Do not edit.\n' + printSchema(schema) + '\n');
await rename(temp, destination);
console.log(`Schema saved (${Object.keys(schema.getTypeMap()).length} types). No customer data or credentials are stored.`);
